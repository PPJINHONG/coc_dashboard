--
ALTER TABLE "ops_regional_issues" ADD CONSTRAINT "resolved_issue_progress_100" CHECK ((NOT ("status" = 'resolved') OR "progress_percent" = 100));
--
-- Create constraint current_issue_valid_status on model regionalissue
--
ALTER TABLE "ops_regional_issues" ADD CONSTRAINT "current_issue_valid_status" CHECK ("status" IN ('open', 'blocked', 'resolved'));
--
-- Create constraint current_issue_valid_severity on model regionalissue
--
ALTER TABLE "ops_regional_issues" ADD CONSTRAINT "current_issue_valid_severity" CHECK ("severity" IN ('critical', 'major', 'minor', 'info'));
--
-- Create constraint work_completed_lte_total on model worksummary
--
ALTER TABLE "ops_work_summaries" ADD CONSTRAINT "work_completed_lte_total" CHECK ("completed_count" <= ("total_count"));
--
-- Create constraint work_batch_lte_total on model worksummary
--
ALTER TABLE "ops_work_summaries" ADD CONSTRAINT "work_batch_lte_total" CHECK ("batch_count" <= ("total_count"));
--
-- Create constraint work_delayed_lte_remaining on model worksummary
--
ALTER TABLE "ops_work_summaries" ADD CONSTRAINT "work_delayed_lte_remaining" CHECK ("delayed_count" <= ("total_count" - "completed_count"));
--
-- Create constraint work_mttr_nonnegative on model worksummary
--
ALTER TABLE "ops_work_summaries" ADD CONSTRAINT "work_mttr_nonnegative" CHECK (("mttr_minutes" IS NULL OR "mttr_minutes" >= 0));
--
-- Create constraint unique_current_work_scope on model worksummary
--
ALTER TABLE "ops_work_summaries" ADD CONSTRAINT "unique_current_work_scope" UNIQUE ("region_id", "work_type", "scope");
--
-- Create constraint current_work_valid_type on model worksummary
--
ALTER TABLE "ops_work_summaries" ADD CONSTRAINT "current_work_valid_type" CHECK ("work_type" IN ('request', 'change', 'incident'));
--
-- Create constraint current_work_valid_scope on model worksummary
--
ALTER TABLE "ops_work_summaries" ADD CONSTRAINT "current_work_valid_scope" CHECK ("scope" IN ('infra', 'automation'));
