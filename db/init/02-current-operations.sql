BEGIN;
--
-- Create model ChangeLog
--
CREATE TABLE "ops_change_logs" ("id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "section" varchar(30) NOT NULL, "action" varchar(30) NOT NULL, "actor_name" varchar(150) NOT NULL, "actor_username" varchar(150) DEFAULT '' NOT NULL, "summary" varchar(300) NOT NULL, "before_data" jsonb DEFAULT '{}'::jsonb NOT NULL, "after_data" jsonb DEFAULT '{}'::jsonb NOT NULL, "created_at" timestamp with time zone DEFAULT (STATEMENT_TIMESTAMP()) NOT NULL);
COMMENT ON TABLE "ops_change_logs" IS '운영 데이터 변경 이력';
--
-- Create model Region
--
CREATE TABLE "ops_regions" ("id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "region_name" varchar(80) NOT NULL UNIQUE, "country_code" varchar(10) DEFAULT 'KR' NOT NULL);
COMMENT ON TABLE "ops_regions" IS '리전 공통데이터';
--
-- Create model Service
--
CREATE TABLE "ops_services" ("service_code" varchar(40) NOT NULL PRIMARY KEY, "service_name" varchar(80) NOT NULL UNIQUE);
COMMENT ON TABLE "ops_services" IS '인프라 서비스 공통데이터';
--
-- Create model StaffMember
--
CREATE TABLE "ops_staff_members" ("id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "staff_name" varchar(100) NOT NULL);
COMMENT ON TABLE "ops_staff_members" IS '운영 인력 공통데이터';
--
-- Create model DataState
--
CREATE TABLE "ops_data_state" ("id" smallint NOT NULL PRIMARY KEY CHECK ("id" >= 0), "revision" integer DEFAULT 0 NOT NULL CHECK ("revision" >= 0), "updated_at" timestamp with time zone DEFAULT (STATEMENT_TIMESTAMP()) NOT NULL);
COMMENT ON TABLE "ops_data_state" IS '운영 데이터 동시 수정 버전';
--
-- Create model RegionalIssue
--
CREATE TABLE "ops_regional_issues" ("id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "updated_at" timestamp with time zone DEFAULT (STATEMENT_TIMESTAMP()) NOT NULL, "title" varchar(200) NOT NULL, "description" text DEFAULT '' NOT NULL, "severity" varchar(10) DEFAULT 'minor' NOT NULL, "status" varchar(10) DEFAULT 'open' NOT NULL, "progress_percent" smallint DEFAULT 0 NOT NULL CHECK ("progress_percent" >= 0), "next_action" text DEFAULT '' NOT NULL, "author_name" varchar(150) DEFAULT '' NOT NULL, "author_username" varchar(150) DEFAULT '' NOT NULL, "region_id" bigint NOT NULL, "owner_staff_id" bigint NULL);
COMMENT ON TABLE "ops_regional_issues" IS '현재 리전별 운영 이슈·조치';
--
-- Create model IssueComment
--
CREATE TABLE "ops_issue_comments" ("id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "author_name" varchar(150) NOT NULL, "author_username" varchar(150) DEFAULT '' NOT NULL, "content" text NOT NULL, "created_at" timestamp with time zone DEFAULT (STATEMENT_TIMESTAMP()) NOT NULL, "issue_id" bigint NOT NULL);
COMMENT ON TABLE "ops_issue_comments" IS '운영 이슈 댓글';
--
-- Create model WorkSummary
--
CREATE TABLE "ops_work_summaries" ("id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "updated_at" timestamp with time zone DEFAULT (STATEMENT_TIMESTAMP()) NOT NULL, "work_type" varchar(10) NOT NULL, "scope" varchar(15) DEFAULT 'infra' NOT NULL, "total_count" integer DEFAULT 0 NOT NULL CHECK ("total_count" >= 0), "completed_count" integer DEFAULT 0 NOT NULL CHECK ("completed_count" >= 0), "batch_count" integer DEFAULT 0 NOT NULL CHECK ("batch_count" >= 0), "delayed_count" integer DEFAULT 0 NOT NULL CHECK ("delayed_count" >= 0), "mttr_minutes" numeric(8, 1) NULL, "remarks" text DEFAULT '' NOT NULL, "region_id" bigint NOT NULL);
COMMENT ON TABLE "ops_work_summaries" IS '현재 요청·변경·장애 작업 현황';
--
-- Create model InfrastructureResource
--
CREATE TABLE "infra_resources" ("id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "updated_at" timestamp with time zone DEFAULT (STATEMENT_TIMESTAMP()) NOT NULL, "environment_name" varchar(80) DEFAULT '운영' NOT NULL, "host_count" integer DEFAULT 0 NOT NULL CHECK ("host_count" >= 0), "vm_count" integer NULL CHECK ("vm_count" >= 0), "storage_count" integer NULL CHECK ("storage_count" >= 0), "remarks" text DEFAULT '' NOT NULL, "region_id" bigint NOT NULL, "service_code" varchar(40) NOT NULL);
COMMENT ON TABLE "infra_resources" IS '현재 인프라 자원: 리전·서비스·환경별 Host·VM·Storage 수량';
--
-- Create model StaffAssignment
--
CREATE TABLE "ops_staff_assignments" ("id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY, "updated_at" timestamp with time zone DEFAULT (STATEMENT_TIMESTAMP()) NOT NULL, "job_title" varchar(100) NOT NULL, "company_name" varchar(100) NOT NULL, "job_description" text DEFAULT '' NOT NULL, "work_location" varchar(150) DEFAULT '' NOT NULL, "country_code" varchar(2) NOT NULL, "staff_member_id" bigint NOT NULL);
COMMENT ON TABLE "ops_staff_assignments" IS '현재 운영 인력 배치';
